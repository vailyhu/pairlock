const Mod = require('../engine/modules');
const items = [{ id: 'p1', image: 'images/1.png', sketch: 'images/s1.png' }, { id: 'p2', image: 'images/2.png', sketch: 'images/s2.png' }, { id: 'p3', image: 'images/3.png', sketch: 'images/s3.png', if: { has: 'i_p3' } }];
const cfg = { type: 'sequence', title: 'Q', sides: { a: 'Képek', b: 'Vázlatok' }, options: { items, slots: ['1', '2', '3'], answer: ['p2', 'p3', 'p1'], checkLabel: 'c', okText: 'ok', badText: 'no', trayLabel: 'tray', sketchText: 'sketches' } };
let bad = 0; const check = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) bad++; console.log(`${ok ? 'ok  ' : 'FAIL'} ${n}: ${JSON.stringify(got)}`); };
const world = { solved: {}, inventory: [] }, r = { solo: false, messages: [], world }; Mod.setPush(() => {});
const W = require('../engine/world'); const realTest = W.test; W.test = (c, w) => c && c.has ? w.inventory.includes(c.has) : realTest(c, w);
const A = m => Mod.act(cfg, 'q', r, 0, m), B = m => Mod.act(cfg, 'q', r, 1, m);
A({ side: 'a' }); B({ side: 'b' });
const va = Mod.view(cfg, 'q', r, 0).view, vb = Mod.view(cfg, 'q', r, 1).view;
check('arranging side has no sketches', 'sketches' in va, false);
check('sketch side cannot arrange', [vb.canArrange, 'slots' in vb], [false, false]);
check('sketch numbers are the slot numbers', vb.sketches.map(s => [s.image, s.number]).sort(), [['images/s1.png', 3], ['images/s2.png', 1], ['images/s3.png', 2]]);
check('arranging view has no answer', JSON.stringify(va).includes('answer'), false);
check('gated item not offered', va.items.map(i => i.id).sort(), ['p1', 'p2']);
check('gated item cannot be placed', A({ item: 'p3', slot: 0 }).view.view.placed, [null, null, null]);
B({ item: 'p1', slot: 0 }); check('sketch side move ignored', Mod.view(cfg, 'q', r, 0).view.placed, [null, null, null]);
A({ item: 'p2', slot: 0 }); A({ item: 'p1', slot: 1 }); A({ item: 'p2', slot: 1 });
check('drop on a taken slot swaps', Mod.view(cfg, 'q', r, 0).view.placed, ['p1', 'p2', null]);

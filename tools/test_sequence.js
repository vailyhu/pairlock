check('placed item stays offered after leaving the inventory', (world.inventory.length = 0, Mod.view(cfg, 'q', r, 0).view.items.length), 3);
w = A({ check: true }); check('right order solves', [w.view.justSolved, w.msgs[0].text], [true, '(GAME: SOLVED, Q)']);
